/** 自由板显示/删除安全契约。合成工程；jsdom不证明真实鼠标或视觉验收。 */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { makeBoardHarness } = require('./board-workspace-test-helper.cjs');
let count = 0;
const check = (label, actual, expected = true) => { assert.deepEqual(actual, expected, label); console.log(`✓ ${label}`); count++; };
let h;
(async () => {
  h = await makeBoardHarness('board-polish');
  const { act, state, clone, q, qa, card, hit, byName, click, key, pressCard, mount, history, menuDelete } = h;
  await mount();
  const original = clone(state().project);
  const initialHistory = history();
  check('默认总览显示全部三条关系线', qa('.board-link__hit').length, 3);
  check('无尺寸场景使用新显示默认高200', card('s1').style.height, '200px');
  check('显式卡片尺寸保持180', card('s2').style.height, '180px');
  check('关系命中路径与可见路径几何一致', hit('l1').getAttribute('d'), hit('l1').parentElement.querySelector('.board-link__stroke').getAttribute('d'));
  check('尺寸视觉兜底不写工程', state().project, original);
  check('连接模式入口具有明确无障碍名称', !!q('.board__dock button[aria-label="连接两张卡片"]'));
  check('常驻卡片连接/删除按钮由工具与右键菜单替代', qa('[data-card] .bcard__connect, [data-card] .bcard__del').length, 0);
  check('场号标题同属紧凑标题行', !!q('.bcard__head .bcard__no + .bcard__title'));
  check('所有缩放入口保留且不显示文字', qa('.bcard__resize').length === 4 && qa('.bcard__resize').every((b) => !b.textContent.trim() && b.getAttribute('aria-label')));
  check('无卡片选中时不显示颜色/关联上下文', q('.board__context'), null);
  await act(async () => state().setSelectedIds(['scene:s1', 'beat:b1']));
  await click(q('.board__dock button[aria-label="连接两张卡片"]'));
  await pressCard('s1');
  // Explicitly seed both visible/hidden selected cards independently of mode UI.
  await act(async () => state().setSelectedIds(['scene:s1', 'beat:b1']));
  await click(byName('灵感板'));
  check('只显示双端可见关系，备注同步过滤', qa('.board-link__label').map((node) => node.textContent.trim()), ['合成灵感关系']);
  check('隐藏场景移出选区', state().selectedIds, ['beat:b1']);
  await pressCard('b2');
  check('切板取消未完成连接', state().project.boardLinks, original.boardLinks);
  check('切板不删除工程关系或写历史', [state().project, history()], [original, initialHistory]);
  await click(byName('场景板'));
  check('场景板仅显示场景间关系', qa('.board-link__label').map((node) => node.textContent.trim()), ['合成场景关系']);
  await click(byName('总览'));
  check('回到总览完整恢复关系备注', qa('.board-link__hit').length, 3);
  await h.openViewSettings();
  const grid = q('input[aria-label="显示网格"]');
  const snap = q('input[aria-label="磁吸网格"]');
  check('显示网格与磁吸有独立可访问开关', !!grid && !!snap);
  check('参考网格默认开启、磁吸默认关闭', [grid.checked, snap.checked], [true, false]);
  check('28单位世界网格初始间距与原点正确', [q('.board__canvas').style.backgroundSize, q('.board__canvas').style.backgroundPosition], ['28px 28px', '0px 0px']);
  await click(grid);
  check('网格开关只改显示', [q('.board__canvas').dataset.grid, state().project, history()], ['off', original, initialHistory]);
  await click(grid);
  await click(snap);
  check('开启磁吸不会搬动旧卡片或写历史', [q('.board--workspace').dataset.snap, state().project, history()], ['on', original, initialHistory]);
  await click(snap);
  await click(byName('放大自由板'));
  check('缩放只变换世界', q('.board__world').style.transform, 'translate(0px, 0px) scale(1.1)');
  check('方格网格间距与世界缩放同步', q('.board__canvas').style.backgroundSize.split(' ').map(parseFloat), [28 * 1.1, 28 * 1.1]);
  await h.dispatch(q('.board__canvas'), new h.w.WheelEvent('wheel', { clientX: 100, clientY: 80, deltaY: -80, bubbles: true, cancelable: true }));
  const translation = q('.board__world').style.transform.match(/translate\(([^,]+), ([^)]+)\)/);
  check('光标缩放时网格原点跟随pan', q('.board__canvas').style.backgroundPosition, `${translation[1]} ${translation[2]}`);
  check('显示与缩放操作不改工程/历史', [state().project, history()], [original, initialHistory]);

  await act(async () => state().setSelectedIds(['beat:b2']));
  const sceneDelete = await menuDelete('s1');
  const selectionBefore = [...state().selectedIds];
  check('场景右键仍明确提供删除整场', sceneDelete.getAttribute('aria-label') === '删除整场' || sceneDelete.textContent.trim() === '删除整场');
  await click(sceneDelete);
  check('场景单卡删除明确警告正文', h.confirmations().length === 1 && h.confirmations()[0].includes('正文'));
  check('取消删除保留正文/关系/选区/历史', [state().project, state().selectedIds, history()], [original, selectionBefore, initialHistory]);
  h.accept(true);
  await click(await menuDelete('s1'));
  check('确认删除整场及其正文', state().project.elements.map((e) => e.id), ['s2', 'a2']);
  check('确认单场保留素材并解除关联', state().project.beats.map((b) => [b.id, b.sceneId]), [['b1', undefined], ['b2', undefined]]);
  check('整场删除仅清理相关关系', state().project.boardLinks.map((link) => link.id), ['l2']);
  check('一次删除只产生一个历史', state().past.length, 1);
  await act(async () => state().undo());
  check('撤销完整恢复正文与关系', state().project, original);

  await mount();
  await act(async () => state().setSelectedIds(['scene:s1', 'beat:b2']));
  const bulkSelection = [...state().selectedIds];
  await key(document.body, 'Delete');
  check('键盘批量含场景也需确认，取消无历史', [h.confirmations().length, state().project, state().selectedIds, state().past.length], [1, original, bulkSelection, 0]);
  h.accept(true);
  await h.mouse(card('s1'), 'contextmenu', { button: 2 });
  const bulkDelete = byName('删除所选（含整场）') || byName('删除所选');
  assert.ok(bulkDelete, 'selected-card context retains a batch deletion entry');
  await click(bulkDelete);
  check('按钮批量删除场景与所选卡片', [state().project.elements.map((e) => e.id), state().project.beats.map((b) => b.id), state().past.length], [['s2', 'a2'], ['b1'], 1]);
  await act(async () => state().undo());
  check('批量删除一次撤销完整恢复', state().project, original);
  await mount();
  await click(byName('灵感板'));
  // 模拟其他视图留下隐藏选区；不依赖切板事件也不能误删隐藏卡片。
  await act(async () => state().setSelectedIds(['scene:s1', 'beat:b2']));
  await key(document.body, 'Backspace');
  check('隐藏选区绝不被键盘误删', state().project.elements, original.elements);
  check('仅删除可见所选灵感，无整场确认', [state().project.beats.map((b) => b.id), h.confirmations().length], [['b1'], 0]);
  await mount();
  await act(async () => state().setSelectedIds(['scene:s1']));
  await key(q('.bcard__scene-notes'), 'Delete');
  await act(async () => state().setSelectedIds(['beat:b1']));
  await key(q('select[aria-label="关联到场景"]'), 'Delete');
  check('编辑摘要/上下文关联选择器Delete不删卡', [state().project, h.confirmations().length], [original, 0]);
  await click(byName('灵感板'));
  await pressCard('b1', { ctrlKey: true });
  await pressCard('b2', { shiftKey: true });
  check('Shift范围选择只覆盖可见卡片', state().selectedIds, ['beat:b1', 'beat:b2']);
  await act(async () => state().setSelectedIds(['scene:s1', 'beat:b1']));
  await click(q('.board__context [aria-label="卡片颜色 1"]'));
  check('隐藏选区不能被改色', state().project.sceneMeta, original.sceneMeta);
  check('可见所选卡片仍能改色', state().project.beats[0].color !== original.beats[0].color);
  const css = fs.readFileSync(path.join(h.repo, 'src/styles/board-polish.css'), 'utf8');
  check('样式限定屏幕与自由板，不影响写作/PDF', css.includes('@media screen') && !/\.editor|\.write-|\.preview|@media print/.test(css));
  const canvasRule = css.match(/(?:^|\n)\s*\.app-shell\[data-theme\]\s+\.board--polished\s+\.board__canvas\s*\{([^{}]*)\}/)?.[1] || '';
  check('自由板自身画布限定overflow clip，避免原生滚动偏移破坏拖动坐标', /(?:^|;)\s*overflow\s*:\s*clip\s*(?:!important\s*)?(?:;|$)/.test(canvasRule));
  check('方格网格保留可关闭屏幕参考', css.includes('linear-gradient(to right') && css.includes('linear-gradient(to bottom') && css.includes('data-grid'));
  check('无React/window运行错误', h.errors, []);
  console.log(`\n自由板显示与删除安全专项：${count} 条通过。jsdom事件/state覆盖；真实拖拽、画面和原生确认另需浏览器验收。`);
})().catch((error) => { console.error(error?.stack || error); process.exitCode = 1; }).finally(async () => { if (h) await h.close(); });
